/**
 * Calculate nutrition for a given food and weight in grams
 */
export const calculateFoodNutrition = (foodKey, weightG) => {
  if (!foodKey) return { calories: 0, protein: 0, carbs: 0, fat: 0 };
  const key = String(foodKey).toLowerCase().trim();
  const entry = FOOD_DATABASE_256[key];
  if (!entry) {
    // Standard default per 100g estimate: 150 kcal, 6g protein, 20g carbs, 4g fat
    const factor = Math.max(0, weightG) / 100.0;
    return {
      calories: Math.round(150 * factor * 10) / 10,
      protein: Math.round(6.0 * factor * 10) / 10,
      carbs: Math.round(20.0 * factor * 10) / 10,
      fat: Math.round(4.0 * factor * 10) / 10,
    };
  }
  const factor = Math.max(0, weightG) / 100.0;
  return {
    calories: Math.round(entry.calories * factor * 10) / 10,
    protein: Math.round(entry.protein * factor * 10) / 10,
    carbs: Math.round(entry.carbs * factor * 10) / 10,
    fat: Math.round(entry.fat * factor * 10) / 10,
  };
};

/**
 * Calculate NutriScore Grade (A to E) based on macronutrient balance
 */
export const calculateNutriScore = (calories, protein, carbs, fat) => {
  const proteinRatio = (protein * 4) / Math.max(1, calories);
  const fatRatio = (fat * 9) / Math.max(1, calories);

  if (proteinRatio >= 0.25 && fatRatio <= 0.35) {
    return { grade: 'A', label: 'Optimal Athletic Nutrition', color: '#10b981' };
  } else if (proteinRatio >= 0.18 && fatRatio <= 0.40) {
    return { grade: 'B', label: 'Balanced & Nutritious', color: '#34d399' };
  } else if (fatRatio <= 0.45) {
    return { grade: 'C', label: 'Moderate Energy Balance', color: '#f59e0b' };
  } else {
    return { grade: 'D', label: 'High Caloric Density', color: '#ef4444' };
  }
};
